// Monta um banco de frases a partir do contexto, sem IA.
window.bancoOffline = function (contexto) {
  const B = window.BANCO_PT;
  const termos = (contexto || "")
    .split(/[,;\n]|\s+e\s+/)
    .map((t) => t.trim())
    .filter(Boolean);
  const encher = (tpls) =>
    termos.length ? tpls.flatMap((t) => termos.map((c) => t.replaceAll("{c}", c))) : [];
  return {
    frases: [...B.frases, ...encher(B.templates), ...encher(B.templates)],
    manchetes: B.manchetes,
    citacoes: [...B.citacoes, ...encher(B.citacoesTpl)],
    comPalavra: [...B.comPalavra.filter((t) => !t.includes("{c}")), ...encher(B.comPalavra.filter((t) => t.includes("{c}")))],
    citacoesPalavra: [...B.citacoesPalavra.filter((t) => !t.includes("{c}")), ...encher(B.citacoesPalavra.filter((t) => t.includes("{c}")))],
    jornais: B.jornais,
    assinaturas: B.assinaturas,
  };
};
